package generator

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"android/soong/android"
)

// Automatic UAPI export kernels need real outputs, not just a stamp: sbox
// removes files absent from copy_after. Keep this opt-in for legacy kernels.
func kernelUapiOutputNames(ctx android.ModuleContext, root, arch, prefix string) ([]string, error) {
	headers := make(map[string]bool)
	for _, tree := range []string{"include/uapi", "arch/" + arch + "/include/uapi"} {
		base := filepath.Join(root, tree)
		files, err := ctx.GlobWithDeps(filepath.Join(base, "**/*.h"), nil)
		if err != nil {
			return nil, err
		}
		for _, file := range files {
			rel, err := filepath.Rel(base, file)
			if err != nil || strings.HasPrefix(rel, "../") {
				return nil, fmt.Errorf("invalid UAPI path %s", file)
			}
			headers[rel] = true
		}
	}
	// asm-generic wrappers are generated by Makefile.asm-generic.
	for _, file := range []string{"include/uapi/asm-generic/Kbuild", "arch/" + arch + "/include/uapi/asm/Kbuild"} {
		data, err := os.ReadFile(filepath.Join(prefix, root, file))
		if err != nil {
			return nil, err
		}
		for _, line := range strings.Split(string(data), "\n") {
			fields := strings.Fields(strings.SplitN(line, "#", 2)[0])
			if len(fields) < 3 || fields[1] != "+=" {
				continue
			}
			if fields[0] != "mandatory-y" && fields[0] != "generic-y" && fields[0] != "generated-y" {
				continue
			}
			for _, name := range fields[2:] {
				if !strings.HasSuffix(name, ".h") || strings.ContainsAny(name, "$()") {
					return nil, fmt.Errorf("unsupported generated UAPI expression %q in %s", name, file)
				}
				headers["asm/"+name] = true
			}
		}
	}
	// Match include/uapi/Kbuild's architecture-dependent exclusions.
	for _, name := range []string{"a.out.h", "kvm.h", "kvm_para.h"} {
		if !headers["asm/"+name] {
			delete(headers, "linux/"+name)
		}
	}
	headers["linux/version.h"] = true
	result := make([]string, 0, len(headers))
	for name := range headers {
		result = append(result, filepath.Join("usr/include", name))
	}
	sort.Strings(result)
	return result, nil
}
